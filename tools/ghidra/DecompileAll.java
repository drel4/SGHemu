// Decompiles every function of the current program into a single C file.
//
// Usage (as a -postScript):
//   DecompileAll.java <output dir> [base name]
//
// Without a base name the program's own name is used (extension stripped), so
// importing several programs in one headless run produces one .c each.  A
// matching <base>.functions.txt index of entry points is written next to it.
//
// @category SGHemu
import ghidra.app.script.GhidraScript;
import ghidra.app.decompiler.*;
import ghidra.program.model.listing.*;
import java.io.*;
import java.util.*;

public class DecompileAll extends GhidraScript {
    @Override
    public void run() throws Exception {
        String[] args = getScriptArgs();
        File outDir = new File(args.length > 0 ? args[0] : ".");
        if (!outDir.isDirectory() && !outDir.mkdirs()) {
            throw new IOException("cannot create output directory: " + outDir);
        }
        String base = args.length > 1 && !args[1].isEmpty()
            ? args[1] : stripExtension(currentProgram.getName());
        File cFile = new File(outDir, base + ".c");
        File indexFile = new File(outDir, base + ".functions.txt");

        FunctionManager manager = currentProgram.getFunctionManager();
        List<Function> functions = new ArrayList<>();
        for (Function function : manager.getFunctions(true)) {
            functions.add(function);
        }
        functions.sort(Comparator.comparing(Function::getEntryPoint));

        DecompInterface decompiler = new DecompInterface();
        decompiler.setOptions(new DecompileOptions());
        decompiler.openProgram(currentProgram);

        long started = System.currentTimeMillis();
        int decompiled = 0;
        int failed = 0;
        try (PrintWriter index = new PrintWriter(new BufferedWriter(new FileWriter(indexFile), 1 << 16));
             PrintWriter out = new PrintWriter(new BufferedWriter(new FileWriter(cFile), 1 << 20))) {
            out.println("/*");
            out.println(" * Program : " + currentProgram.getName());
            out.println(" * Language: " + currentProgram.getLanguageID() + " / " + currentProgram.getCompilerSpec().getCompilerSpecID());
            out.println(" * Functions: " + functions.size());
            out.println(" * Generated by tools/ghidra/DecompileAll.java");
            out.println(" */");
            out.println();
            int total = functions.size();
            for (int i = 0; i < total; ++i) {
                Function function = functions.get(i);
                index.println(function.getEntryPoint() + "\t" + function.getName());
                out.println("/* ---- [" + (i + 1) + "/" + total + "] "
                    + function.getEntryPoint() + " " + function.getName() + " ---- */");
                DecompileResults result = decompiler.decompileFunction(function, 60, monitor);
                if (result != null && result.decompileCompleted()) {
                    out.println(result.getDecompiledFunction().getC().trim());
                    ++decompiled;
                }
                else {
                    out.println("/* DECOMPILE FAILED: "
                        + (result == null ? "no result" : result.getErrorMessage()) + " */");
                    ++failed;
                }
                out.println();
                if ((i + 1) % 500 == 0) {
                    println("[" + currentProgram.getName() + "] " + (i + 1) + "/" + total);
                }
            }
        }
        finally {
            decompiler.dispose();
        }
        println("wrote " + cFile + " (" + decompiled + " decompiled, " + failed
            + " failed) in " + ((System.currentTimeMillis() - started) / 1000) + "s");
    }

    private static String stripExtension(String name) {
        int dot = name.lastIndexOf('.');
        return dot > 0 ? name.substring(0, dot) : name;
    }
}
